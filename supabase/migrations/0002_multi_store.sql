-- Multi-store (multi-tenant) foundation.
--
-- Turns a single-store schema into a platform: one `stores` row per business,
-- every content row owned by exactly one store, and RLS that scopes each admin
-- to the store(s) they belong to.
--
-- Fashion Factory Nepal is migrated in as the default store, with its existing
-- products, categories and branches attached to it. Nothing is lost: the
-- singleton `store_settings` row is copied into `stores` before that table is
-- dropped, in this same transaction.
--
-- Deployment model: ONE codebase, one build per store. The storefront reads
-- committed JSON generated by scripts/generate-site-data.mjs, which takes a
-- STORE_SLUG and emits that store's data. Adding a store is a row here plus a
-- deployment pointed at that slug — never a fork of the application.

-- ---------------------------------------------------------------------------
-- Stores
-- ---------------------------------------------------------------------------

create table if not exists public.stores (
  id uuid primary key default gen_random_uuid(),

  -- Identity. `slug` is the tenant key used by STORE_SLUG at publish time, so
  -- it has to stay URL- and env-var-safe.
  slug text not null unique
    constraint stores_slug_format check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null,
  legal_name text,
  tagline text,
  description text,

  -- Brand assets. URLs rather than uploads so a store can point at anything
  -- public (its own storage folder, a CDN, an existing site).
  logo_url text,
  favicon_url text,

  -- Contact. phone is stored as dialled; whatsapp_number is digits-only with
  -- country code, because wa.me rejects anything else — the same split the
  -- storefront's telHref/whatsappHref helpers expect.
  phone text not null,
  whatsapp_number text not null
    constraint stores_whatsapp_digits check (whatsapp_number ~ '^\d{6,15}$'),
  email text,

  -- Social. Handle and URL are stored separately: the handle is displayed
  -- verbatim (it may be styled, e.g. "Fashionfactory@99") while the URL is what
  -- is actually linked, so the site never has to guess one from the other.
  instagram_handle text,
  instagram_url text,
  tiktok_handle text,
  tiktok_url text,
  facebook_url text,

  -- Place and hours. `opening_hours` is the human string shown on the site;
  -- `business_hours` is the structured form for schema.org and future
  -- open/closed logic, e.g. [{"days":["Mo","Tu"],"opens":"09:00","closes":"17:00"}].
  location_label text not null,
  address text,
  country_code text not null default 'NP',
  currency text not null default 'NPR',
  opening_hours text not null,
  business_hours jsonb not null default '[]'::jsonb,

  -- Presentation and capability toggles, kept as jsonb so a new theme token or
  -- feature flag does not need a migration on every store's behalf. Shapes are
  -- documented and validated in the application layer (src/models).
  branding jsonb not null default '{}'::jsonb,
  features jsonb not null default '{}'::jsonb,

  -- Storefront copy that names specific places, so it cannot be a literal in
  -- the page. A newline inside visit_title becomes a line break in the heading.
  visit_title text,
  visit_step_body text,

  -- Search metadata. Explicit rather than derived from name + tagline: the
  -- title tag and keyword set are the store's own SEO decisions, and a
  -- generated approximation would quietly replace them.
  seo_title text,
  seo_description text,
  seo_keywords text[] not null default '{}',

  site_url text,

  is_active boolean not null default true,
  is_default boolean not null default false,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- At most one default store. A partial unique index rather than a check
-- constraint, because the rule is across rows, not within one.
create unique index if not exists stores_one_default_idx
  on public.stores ((is_default)) where is_default;

create index if not exists stores_active_idx on public.stores (is_active);

alter table public.stores enable row level security;

